"""Builds the tiny ONNX graph used for beam search: top-k of log_softmax(logits).

Output is embedded (base64) in src/topk-graph.ts so users never need Python.
    python scripts/make-topk-graph.py > src/topk-graph.ts
"""
import base64
import onnx
from onnx import TensorProto, helper

logits = helper.make_tensor_value_info("logits", TensorProto.FLOAT, ["rows", "vocab"])
k = helper.make_tensor_value_info("k", TensorProto.INT64, [1])
values = helper.make_tensor_value_info("values", TensorProto.FLOAT, ["rows", "k"])
indices = helper.make_tensor_value_info("indices", TensorProto.INT64, ["rows", "k"])
graph = helper.make_graph(
    [
        helper.make_node("LogSoftmax", ["logits"], ["logprobs"], axis=-1),
        helper.make_node("TopK", ["logprobs", "k"], ["values", "indices"], axis=-1, largest=1, sorted=1),
    ],
    "beam_topk",
    [logits, k],
    [values, indices],
)
model = helper.make_model(graph, opset_imports=[helper.make_opsetid("", 13)], producer_name="locale-ai")
model.ir_version = 7
onnx.checker.check_model(model)
b64 = base64.b64encode(model.SerializeToString()).decode()
print("// Generated by scripts/make-topk-graph.py: top-k over log_softmax(logits) for beam search.")
print(f'export const TOPK_GRAPH = "{b64}";')
